const GLYPH_COLUMNS = 7;

export type Dot = "on" | "off" | "gap";

function glyphOf(ch: string): readonly string[] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS["."]!;
}

function dotRows(text: string): Dot[][] {
  const glyphs = [...text].map(glyphOf);
  return [0, 1, 2, 3, 4].map((row) =>
    glyphs.flatMap((glyph): Dot[] => [...[...glyph[row]!].map((pixel): Dot => (pixel === "#" ? "on" : "off")), "gap"]),
  );
}

export function dotMatrixRows(text: string, columns: number): Dot[][] | null {
  const maxChars = Math.floor(columns / GLYPH_COLUMNS);
  const words = text.trim().split(/\s+/);
  if (maxChars < 1 || words.some((word) => word.length > maxChars)) return null;

  const lines: string[] = [];
  for (const word of words) {
    const current = lines.at(-1);
    if (current !== undefined && current.length + 1 + word.length <= maxChars) {
      lines[lines.length - 1] = `${current} ${word}`;
    } else {
      lines.push(word);
    }
  }
  if (lines.length > 2) return null;

  return lines.flatMap((line, i) => (i === 0 ? dotRows(line) : [[], ...dotRows(line)]));
}
